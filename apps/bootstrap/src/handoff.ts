/**
 * The configuration bootstrap hands to the apps through the shared /config directory (docs/README.md §4.2):
 * one env file per BFF (sourced by the container entrypoint or loaded by Tilt), one for every API, and
 * seed.json with the seeded users' Zitadel IDs and the IDs of the §6.3 scenario, for the end-to-end tests.
 */
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseEnv } from 'node:util';

import { type Scenario } from './seed';
import { type AppKey } from './zitadel';

/**
 * What a BFF's env file is made of: the client ID Zitadel generated, the public URL it was registered with, and
 * the key of its private-key JWT client authentication (docs/README.md §4.4), the one copy of the private half.
 */
export interface WebApp {
  clientId: string;
  url: string;
  key: AppKey;
}

export interface Handoff {
  issuer: string;
  jwksUrl: string;
  userinfoUrl: string;
  projectId: string;
  dashboardWeb: WebApp;
  tenancyWeb: WebApp;
  dashboardApiUrl: string;
  tenancyApiUrl: string;
  users: Record<string, { id: string; email: string }>;
  scenario: Scenario;
}

/** The env contract of `packages/auth` (ticket 8) plus where the BFF reaches the two APIs; one file per BFF. */
export function webAppEnv(app: WebApp, handoff: Handoff): Record<string, string> {
  return {
    OIDC_ISSUER: handoff.issuer,
    OIDC_CLIENT_ID: app.clientId,
    // The credential: the key ID the assertion's `kid` names, and the PKCS#8 PEM as one base64 line, since the
    // file is sourced by a shell. The file is the one place the private key exists outside the app's memory.
    OIDC_CLIENT_KEY_ID: app.key.keyId,
    OIDC_CLIENT_KEY: Buffer.from(app.key.privateKeyPem, 'utf8').toString('base64'),
    OIDC_REDIRECT_URI: `${app.url}/auth/callback`,
    OIDC_POST_LOGOUT_REDIRECT_URI: `${app.url}/`,
    // The app's public URL, for packages/auth: cookie attributes and the same-origin check (ticket 8).
    APP_URL: app.url,
    // Both BFFs call both APIs (docs/README.md §6.4: the two provisioning calls; §6.5: every documents operation).
    DASHBOARD_API_URL: handoff.dashboardApiUrl,
    TENANCY_API_URL: handoff.tenancyApiUrl,
  };
}

export function apisEnv(handoff: Handoff): Record<string, string> {
  return {
    OIDC_ISSUER: handoff.issuer,
    OIDC_PROJECT_ID: handoff.projectId,
    OIDC_JWKS_URL: handoff.jwksUrl,
    // Where tenancy-api resolves a new user's email and name from the token (docs/README.md §6.4).
    OIDC_USERINFO_URL: handoff.userinfoUrl,
  };
}

// The files are sourced by a POSIX shell without quoting, so a value is limited to characters that need none.
const SAFE_VALUE = /^[A-Za-z0-9._~:/?#@!$&'()*+,;=%-]*$/;

export function renderEnvFile(values: Record<string, string>): string {
  const lines = ['# Generated by the bootstrap container; regenerated on every run. Do not edit.'];
  for (const [key, value] of Object.entries(values)) {
    if (!/^[A-Z][A-Z0-9_]*$/.test(key)) throw new Error(`invalid env file key: ${key}`);
    if (!SAFE_VALUE.test(value) || value.includes("'") || value.includes('$')) {
      throw new Error(`value of ${key} needs shell quoting, which the env files do not support`);
    }
    lines.push(`${key}=${value}`);
  }
  return `${lines.join('\n')}\n`;
}

/**
 * The key the previous run handed to a BFF, read back from its env file before the file is rewritten, so a key
 * Zitadel still lists is carried over rather than replaced (`ensureAppKey`). `undefined` when there is no file
 * or it names no key; any other failure to read the file propagates.
 */
export async function readHeldKey(dir: string, app: string): Promise<AppKey | undefined> {
  let text: string;
  try {
    text = await readFile(path.join(dir, `${app}.env`), 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
    throw error;
  }
  const values = parseEnv(text);
  const keyId = values.OIDC_CLIENT_KEY_ID;
  const encoded = values.OIDC_CLIENT_KEY;
  if (!keyId || !encoded) return undefined;
  const privateKeyPem = Buffer.from(encoded, 'base64').toString('utf8');
  if (!privateKeyPem.startsWith('-----BEGIN PRIVATE KEY-----')) return undefined;
  return { keyId, privateKeyPem };
}

/** Writes the handoff files, each through a temporary file and a rename so a reader never sees a partial file. */
export async function writeHandoff(dir: string, handoff: Handoff): Promise<string[]> {
  await mkdir(dir, { recursive: true });
  const files: Record<string, string> = {
    'dashboard-web.env': renderEnvFile(webAppEnv(handoff.dashboardWeb, handoff)),
    'tenancy-web.env': renderEnvFile(webAppEnv(handoff.tenancyWeb, handoff)),
    'apis.env': renderEnvFile(apisEnv(handoff)),
    'seed.json': `${JSON.stringify({ users: handoff.users, ...handoff.scenario }, null, 2)}\n`,
  };
  for (const [name, content] of Object.entries(files)) {
    const target = path.join(dir, name);
    const temporary = `${target}.tmp`;
    await writeFile(temporary, content, { encoding: 'utf8', mode: 0o644 });
    await rename(temporary, target);
  }
  return Object.keys(files);
}
