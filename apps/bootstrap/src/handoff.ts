/**
 * The configuration bootstrap hands to the apps through the shared /config directory (docs/README.md §4.2):
 * one env file per app (sourced by the container entrypoint or loaded by Tilt), one for every API, and
 * seed.json with the Zitadel IDs the seeds of ticket 12 need.
 */
import { mkdir, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';

export interface Handoff {
  issuer: string;
  jwksUrl: string;
  projectId: string;
  dashboardWeb: { clientId: string; url: string };
  tenancyApiUrl: string;
  users: Record<string, { id: string; email: string }>;
}

export function dashboardWebEnv(handoff: Handoff): Record<string, string> {
  return {
    OIDC_ISSUER: handoff.issuer,
    OIDC_CLIENT_ID: handoff.dashboardWeb.clientId,
    OIDC_REDIRECT_URI: `${handoff.dashboardWeb.url}/auth/callback`,
    OIDC_POST_LOGOUT_REDIRECT_URI: `${handoff.dashboardWeb.url}/`,
    TENANCY_API_URL: handoff.tenancyApiUrl,
  };
}

export function apisEnv(handoff: Handoff): Record<string, string> {
  return {
    OIDC_ISSUER: handoff.issuer,
    OIDC_PROJECT_ID: handoff.projectId,
    OIDC_JWKS_URL: handoff.jwksUrl,
  };
}

// The files are sourced by a POSIX shell without quoting, so a value is limited to characters that need none.
const SAFE_VALUE = /^[A-Za-z0-9._~:/?#@!$&'()*+,;=%-]*$/;

export function renderEnvFile(values: Record<string, string>): string {
  const lines = ['# Generated by the bootstrap container; regenerated on every run. Do not edit.'];
  for (const [key, value] of Object.entries(values)) {
    if (!/^[A-Z][A-Z0-9_]*$/.test(key)) throw new Error(`invalid env file key: ${key}`);
    if (!SAFE_VALUE.test(value) || value.includes("'") || value.includes('$')) {
      throw new Error(`value of ${key} needs shell quoting, which the env files do not support`);
    }
    lines.push(`${key}=${value}`);
  }
  return `${lines.join('\n')}\n`;
}

/** Writes the handoff files, each through a temporary file and a rename so a reader never sees a partial file. */
export async function writeHandoff(dir: string, handoff: Handoff): Promise<string[]> {
  await mkdir(dir, { recursive: true });
  const files: Record<string, string> = {
    'dashboard-web.env': renderEnvFile(dashboardWebEnv(handoff)),
    'apis.env': renderEnvFile(apisEnv(handoff)),
    'seed.json': `${JSON.stringify({ users: handoff.users }, null, 2)}\n`,
  };
  for (const [name, content] of Object.entries(files)) {
    const target = path.join(dir, name);
    const temporary = `${target}.tmp`;
    await writeFile(temporary, content, { encoding: 'utf8', mode: 0o644 });
    await rename(temporary, target);
  }
  return Object.keys(files);
}
