import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from '@jest/globals';

import { apisEnv, dashboardWebEnv, renderEnvFile, writeHandoff, type Handoff } from './handoff';

const handoff: Handoff = {
  issuer: 'http://auth.localtest.me:8080',
  jwksUrl: 'http://auth.localtest.me:8080/oauth/v2/keys',
  userinfoUrl: 'http://auth.localtest.me:8080/oidc/v1/userinfo',
  projectId: '123',
  dashboardWeb: { clientId: '456', url: 'http://dashboard.localtest.me:3000' },
  tenancyApiUrl: 'http://tenancy-api:4001',
  users: { alice: { id: '789', email: 'alice@example.com' } },
};

describe('renderEnvFile', () => {
  it('writes one KEY=value line per entry under a generated header', () => {
    expect(renderEnvFile({ A: '1', B_C: 'http://x/y?z=1' })).toBe(
      '# Generated by the bootstrap container; regenerated on every run. Do not edit.\nA=1\nB_C=http://x/y?z=1\n',
    );
  });

  it('rejects values a shell would mangle and keys a shell cannot export', () => {
    expect(() => renderEnvFile({ A: 'two words' })).toThrow(/needs shell quoting/);
    expect(() => renderEnvFile({ A: '$HOME' })).toThrow(/needs shell quoting/);
    expect(() => renderEnvFile({ 'bad-key': 'x' })).toThrow(/invalid env file key/);
  });
});

describe('env files', () => {
  it('builds the dashboard-web redirect URIs from the public URL', () => {
    expect(dashboardWebEnv(handoff)).toEqual({
      OIDC_ISSUER: 'http://auth.localtest.me:8080',
      OIDC_CLIENT_ID: '456',
      OIDC_REDIRECT_URI: 'http://dashboard.localtest.me:3000/auth/callback',
      OIDC_POST_LOGOUT_REDIRECT_URI: 'http://dashboard.localtest.me:3000/',
      APP_URL: 'http://dashboard.localtest.me:3000',
      TENANCY_API_URL: 'http://tenancy-api:4001',
    });
  });

  it('gives the APIs the issuer, the project ID as audience, the JWKS URL, and the userinfo URL', () => {
    expect(apisEnv(handoff)).toEqual({
      OIDC_ISSUER: 'http://auth.localtest.me:8080',
      OIDC_PROJECT_ID: '123',
      OIDC_JWKS_URL: 'http://auth.localtest.me:8080/oauth/v2/keys',
      OIDC_USERINFO_URL: 'http://auth.localtest.me:8080/oidc/v1/userinfo',
    });
  });
});

describe('writeHandoff', () => {
  let dir: string;
  beforeEach(async () => {
    dir = await mkdtemp(path.join(tmpdir(), 'bootstrap-handoff-'));
  });
  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it('writes the three files and no temporary files', async () => {
    const files = await writeHandoff(path.join(dir, 'config'), handoff);
    expect(files.sort()).toEqual(['apis.env', 'dashboard-web.env', 'seed.json']);
    const seed = JSON.parse(
      await readFile(path.join(dir, 'config', 'seed.json'), 'utf8'),
    ) as unknown;
    expect(seed).toEqual({ users: { alice: { id: '789', email: 'alice@example.com' } } });
    await expect(readFile(path.join(dir, 'config', 'seed.json.tmp'))).rejects.toThrow();
  });
});
