#!/usr/bin/env bash
# Ticket 3 spike. Registers the project and the dashboard-web OIDC application in the running Zitadel through
# the management API (as the bootstrap machine user) and writes .local/config/dashboard-web.env for the app.
# Idempotent: finds by name before creating, so it can run after every `docker compose up`. The bootstrap
# container of ticket 4 replaces this script.
set -euo pipefail
cd "$(dirname "$0")/../.."

env_value() { grep "^$1=" .env | head -1 | cut -d= -f2-; }
ZITADEL_URL="http://$(env_value ZITADEL_DOMAIN):$(env_value ZITADEL_EXTERNALPORT)"
PROJECT_NAME=auth-stack-exercise
APP_NAME=dashboard-web
APP_URL=http://dashboard.localtest.me:3000

# The PAT lives only in the zitadel-bootstrap volume; read it through a container that mounts it. Never echo it.
PAT=$(docker compose exec -T zitadel-login cat /bootstrap/bootstrap.pat | tr -d '\r\n')

api() {
  curl --silent --show-error --fail-with-body \
    --header "Authorization: Bearer $PAT" --header "Content-Type: application/json" "$@"
}
json() { python3 -c "import json,sys; d=json.load(sys.stdin); print($1)"; }

project_id=$(api --request POST "$ZITADEL_URL/management/v1/projects/_search" \
  --data "{\"queries\":[{\"nameQuery\":{\"name\":\"$PROJECT_NAME\",\"method\":\"TEXT_QUERY_METHOD_EQUALS\"}}]}" \
  | json '(d.get("result") or [{}])[0].get("id","")')
if [ -z "$project_id" ]; then
  project_id=$(api --request POST "$ZITADEL_URL/management/v1/projects" --data "{\"name\":\"$PROJECT_NAME\"}" | json 'd["id"]')
  echo "created project $PROJECT_NAME ($project_id)"
else
  echo "project $PROJECT_NAME exists ($project_id)"
fi

client_id=$(api --request POST "$ZITADEL_URL/management/v1/projects/$project_id/apps/_search" \
  --data "{\"queries\":[{\"nameQuery\":{\"name\":\"$APP_NAME\",\"method\":\"TEXT_QUERY_METHOD_EQUALS\"}}]}" \
  | json '(d.get("result") or [{}])[0].get("oidcConfig",{}).get("clientId","")')
if [ -z "$client_id" ]; then
  # Web application, PKCE without a secret, code + refresh token, JWT access tokens, userinfo claims in the ID
  # token. devMode allows the http redirect URI on a host other than localhost.
  client_id=$(api --request POST "$ZITADEL_URL/management/v1/projects/$project_id/apps/oidc" --data "{
    \"name\": \"$APP_NAME\",
    \"redirectUris\": [\"$APP_URL/auth/callback\"],
    \"postLogoutRedirectUris\": [\"$APP_URL/\"],
    \"responseTypes\": [\"OIDC_RESPONSE_TYPE_CODE\"],
    \"grantTypes\": [\"OIDC_GRANT_TYPE_AUTHORIZATION_CODE\", \"OIDC_GRANT_TYPE_REFRESH_TOKEN\"],
    \"appType\": \"OIDC_APP_TYPE_WEB\",
    \"authMethodType\": \"OIDC_AUTH_METHOD_TYPE_NONE\",
    \"accessTokenType\": \"OIDC_TOKEN_TYPE_JWT\",
    \"idTokenUserinfoAssertion\": true,
    \"devMode\": true
  }" | json 'd["clientId"]')
  echo "created application $APP_NAME"
else
  echo "application $APP_NAME exists"
fi

mkdir -p .local/config
cat > .local/config/dashboard-web.env <<ENV
# Generated by scripts/spike/register-dashboard-web.sh; sourced by the dashboard-web container at start.
OIDC_ISSUER=$ZITADEL_URL
OIDC_CLIENT_ID=$client_id
OIDC_REDIRECT_URI=$APP_URL/auth/callback
OIDC_POST_LOGOUT_REDIRECT_URI=$APP_URL/
ENV
echo "wrote .local/config/dashboard-web.env"
