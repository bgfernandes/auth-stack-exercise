#!/bin/sh
# The `tls` one-shot of docker-compose.yml (docs/README.md §4.2): a development certificate authority and the
# certificate Traefik serves for Zitadel's hostname, written to $TLS_DIR (./.local/tls on the host, gitignored),
# plus the dynamic configuration that tells Traefik where they are. Runs on every `up` and is idempotent: the CA is
# created when absent and never touched afterwards (it is what a reviewer imports into a browser once); the
# certificate is issued when absent, when it stops verifying against the CA, or within 30 days of expiry. The
# Traefik file is written last, atomically, because Traefik watches the directory and loads the certificate the
# moment the file appears, which is how a Traefik that started before this script finished (Tilt) catches up.
set -eu

DIR=${TLS_DIR:-/tls}
HOST=${TLS_HOSTNAME:?the hostname the certificate is for}
CA_KEY=$DIR/ca.key
CA_CRT=$DIR/ca.crt
KEY=$DIR/$HOST.key
CRT=$DIR/$HOST.crt
# Container-side paths, as Traefik mounts the same directory at /tls.
TRAEFIK_DIR=/tls

ecdsa_key='ec -pkeyopt ec_paramgen_curve:prime256v1'

if [ -s "$CA_KEY" ] && [ -s "$CA_CRT" ]; then
  echo "tls.ca exists $CA_CRT"
else
  # shellcheck disable=SC2086
  openssl req -x509 -newkey $ecdsa_key -noenc -keyout "$CA_KEY" -out "$CA_CRT" -days 3650 \
    -subj "/CN=auth-stack development CA" \
    -addext "basicConstraints=critical,CA:TRUE,pathlen:0" \
    -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
  # A new CA signs a new certificate.
  rm -f "$KEY" "$CRT"
  echo "tls.ca created $CA_CRT"
fi

if [ -s "$KEY" ] && [ -s "$CRT" ] \
  && openssl verify -CAfile "$CA_CRT" "$CRT" >/dev/null 2>&1 \
  && openssl x509 -in "$CRT" -noout -checkend $((30 * 86400)) >/dev/null; then
  echo "tls.certificate exists $CRT"
else
  # What browsers require of a server certificate (macOS enforces all three for every CA, even a trusted private
  # one): a subject alternative name, the serverAuth usage, and a validity of at most 825 days.
  CSR=$DIR/$HOST.csr
  # shellcheck disable=SC2086
  openssl req -new -newkey $ecdsa_key -noenc -keyout "$KEY" -out "$CSR" \
    -subj "/CN=$HOST" \
    -addext "subjectAltName=DNS:$HOST" \
    -addext "extendedKeyUsage=serverAuth" \
    -addext "basicConstraints=CA:FALSE" 2>/dev/null
  openssl x509 -req -in "$CSR" -CA "$CA_CRT" -CAkey "$CA_KEY" -CAcreateserial -days 825 \
    -copy_extensions copy -out "$CRT" 2>/dev/null
  rm -f "$CSR"
  echo "tls.certificate created $CRT"
fi

chmod 600 "$CA_KEY" "$KEY"
chmod 644 "$CA_CRT" "$CRT"

# Traefik's dynamic configuration (file provider): the one certificate, also the default so that a client without
# SNI gets it rather than Traefik's built-in self-signed one.
cat > "$DIR/traefik.yml.tmp" <<YAML
# Generated by docker/tls/generate.sh on every start. Do not edit.
tls:
  certificates:
    - certFile: $TRAEFIK_DIR/$HOST.crt
      keyFile: $TRAEFIK_DIR/$HOST.key
  stores:
    default:
      defaultCertificate:
        certFile: $TRAEFIK_DIR/$HOST.crt
        keyFile: $TRAEFIK_DIR/$HOST.key
YAML
mv "$DIR/traefik.yml.tmp" "$DIR/traefik.yml"
echo "tls.traefik written $DIR/traefik.yml"
